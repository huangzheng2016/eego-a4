// 取字符字形：ASCII 直接映射（小写→大写），其余返回占位框
const uint8_t* glyphFor(uint32_t codepoint) {
    if (codepoint >= 'a' && codepoint <= 'z') {
        codepoint -= ('a' - 'A');
    }
    if (codepoint >= 0x20 && codepoint <= 0x5F) {
        return GLYPHS[codepoint - 0x20];
    }
    return GLYPH_NOTDEF;
}

// UTF-8 解码下一个码点（非法序列按单字节占位处理并推进 1 字节）
uint32_t nextCodepoint(const uint8_t*& p) {
    uint32_t c = *p++;
    if (c < 0x80) return c;
    if ((c & 0xE0) == 0xC0 && (*p & 0xC0) == 0x80) {
        c = ((c & 0x1F) << 6) | (*p++ & 0x3F);
        return c;
    }
    if ((c & 0xF0) == 0xE0 && (p[0] & 0xC0) == 0x80 && (p[1] & 0xC0) == 0x80) {
        c = ((c & 0x0F) << 12) | ((p[0] & 0x3F) << 6) | (p[1] & 0x3F);
        p += 2;
        return c;
    }
    if ((c & 0xF8) == 0xF0 && (p[0] & 0xC0) == 0x80 && (p[1] & 0xC0) == 0x80 &&
        (p[2] & 0xC0) == 0x80) {
        c = ((c & 0x07) << 18) | ((p[0] & 0x3F) << 12) | ((p[1] & 0x3F) << 6) |
            (p[2] & 0x3F);
        p += 3;
        return c;
    }
    return 0xFFFD;  // 非法序列：占位
}

void drawGlyph(PortraitCanvas& canvas, int16_t x, int16_t y, const uint8_t* glyph,
               int16_t scale, uint8_t gray) {
    for (int16_t col = 0; col < FALLBACK_GLYPH_W; col++) {
        const uint8_t bits = glyph[col];
        for (int16_t row = 0; row < FALLBACK_GLYPH_H; row++) {
            if (!((bits >> row) & 1)) continue;
            const int16_t px = x + col * scale;
            const int16_t py = y + row * scale;
            if (gray == 0) {
                if (scale == 1) {
                    canvas.drawPixel(px, py, 0);
                } else {
                    canvas.fillRect(px, py, scale, scale, 0);
                }
            } else {
                for (int16_t sy = 0; sy < scale; sy++)
                    for (int16_t sx = 0; sx < scale; sx++)
                        canvas.drawPixelGray(px + sx, py + sy, gray);
            }
        }
    }
}

