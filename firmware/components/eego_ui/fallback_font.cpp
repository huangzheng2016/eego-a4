int16_t fallbackTextWidth(const char* utf8, int16_t scale) {
    if (!utf8 || scale < 1) return 0;
    int16_t chars = 0;
    const uint8_t* p = reinterpret_cast<const uint8_t*>(utf8);
    while (*p) {
        nextCodepoint(p);
        chars++;
    }
    return chars * FALLBACK_ADVANCE * scale;
}

int16_t fallbackDrawText(PortraitCanvas& canvas, int16_t x, int16_t y,
                         const char* utf8, int16_t scale, uint8_t gray) {
    if (!utf8) return x;
    if (scale < 1) scale = 1;
    if (gray > 15) gray = 15;
    int16_t cx = x;
    const uint8_t* p = reinterpret_cast<const uint8_t*>(utf8);
    while (*p) {
        const uint32_t cp = nextCodepoint(p);
        drawGlyph(canvas, cx, y, glyphFor(cp), scale, gray);
        cx += FALLBACK_ADVANCE * scale;
    }
    return cx;
}

